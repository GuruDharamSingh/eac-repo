#!/usr/bin/env python3
"""Regenerates the `chn-*` fallback section at the end of packages/content/src/content.css
from apps/arts-collective/src/components/channel/channel.css.

Run from the repo root:  python3 scripts/content-css-fallback.py

Why: the lifted atoms (lightbox, bricks, thumbs, tags, marks, timeline) keep Channel's
class names. Channel styles them with its own stylesheet; any other host gets these rules
instead, at zero added specificity (`:where(.eac-c)`), with --ch-* tokens renamed --ec-*.
"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "apps/arts-collective/src/components/channel/channel.css").read_text()
out_path = root / "packages/content/src/content.css"
out = out_path.read_text()
MARK = "/* ── chn-* fallback"

# Selectors (the part before `{`) that start with one of these are lifted.
KEEP = [
    ".chn-sr", ".chn-idm", ".chn-oi", ".chn-sm[", ".chn-marks", ".chn-thumb", ".chn-kind ", ".chn-kind{",
    ".chn-kicker", ".chn-quiet", ".chn-link ", ".chn-iconbtn", ".chn-btn", ".chn-actions", ".chn-seg",
    ".chn-tag", ".chn-timeline", ".chn-tl-", ".chn-empty-line", ".chn-search", ".chn-brick", ".chn-lightbox",
    ".chn-count", ".chn-help",
]

def strip_comments(t):
    return re.sub(r"/\*.*?\*/", "", t, flags=re.S)

def top_level_rules(t):
    """Yield (selector, body) for top-level rules; yield (`@media ...`, inner) for at-rules."""
    i, n = 0, len(t)
    while i < n:
        j = t.find("{", i)
        if j < 0:
            break
        sel = t[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if t[k] == "{":
                depth += 1
            elif t[k] == "}":
                depth -= 1
            k += 1
        yield sel, t[j + 1 : k - 1].strip()
        i = k

def lifted(sel):
    parts = [p.strip() for p in sel.split(",")]
    return all(any(p.startswith(k) or (p + " ").startswith(k) for k in KEEP) for p in parts)

def scope(sel):
    return ", ".join(":where(.eac-c) " + p.strip() for p in sel.split(","))

def tok(body):
    return body.replace("--ch-", "--ec-")

css = strip_comments(src)
rules = []
mobile = []
for sel, body in top_level_rules(css):
    if sel.startswith("@media"):
        if "max-width" in sel:
            for s2, b2 in top_level_rules(body):
                if lifted(s2):
                    mobile.append((sel, s2, b2))
        continue
    if sel.startswith("@") or sel.startswith(":") or "{" in sel:
        continue
    if lifted(sel):
        rules.append((sel, body))

lines = [MARK + " (generated by scripts/content-css-fallback.py) ─ */"]
for sel, body in rules:
    lines.append(f"{scope(sel)} {{ {' '.join(tok(body).split())} }}")
by_media = {}
for m, s2, b2 in mobile:
    by_media.setdefault(m, []).append((s2, b2))
for m, rs in by_media.items():
    lines.append(m + " {")
    for s2, b2 in rs:
        lines.append(f"  {scope(s2)} {{ {' '.join(tok(b2).split())} }}")
    lines.append("}")

head = out.split(MARK)[0] if MARK in out else out.rstrip() + "\n\n"
out_path.write_text(head + "\n".join(lines) + "\n")
print(f"lifted {len(rules)} rules and {len(mobile)} mobile rules")
