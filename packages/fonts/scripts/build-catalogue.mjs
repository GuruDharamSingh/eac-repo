#!/usr/bin/env node
// Regenerates src/catalogue.ts from Google Fonts' public metadata.
//
//   curl -s -o /tmp/gf.json https://fonts.google.com/metadata/fonts
//   node packages/fonts/scripts/build-catalogue.mjs /tmp/gf.json > packages/fonts/src/catalogue.ts
//
// The list is curated, not exhaustive: Latin open-source families only, no
// colour or brand fonts, the most-used N per category by Google's popularity
// rank, plus every family a site or style family already names (FORCE) and a
// hand-picked blackletter group. Weights and italics come straight from the
// metadata, so a stylesheet URL built from an entry never asks Google for a
// weight the family does not have (which fails the whole request).

import { readFileSync } from "node:fs";

const src = process.argv[2];
if (!src) { console.error("usage: build-catalogue.mjs <metadata.json>"); process.exit(1); }
const meta = JSON.parse(readFileSync(src, "utf8")).familyMetadataList;

const PER_CATEGORY = { serif: 120, sans: 150, display: 110, script: 70, mono: 35 };
const CATEGORY = { "Serif": "serif", "Sans Serif": "sans", "Display": "display", "Handwriting": "script", "Monospace": "mono" };
const BLACKLETTER = ["UnifrakturMaguntia", "UnifrakturCook", "Pirata One", "Grenze Gotisch", "New Rocker", "Germania One", "Fruktur", "Jacquard 12", "Jacquard 24", "Jacquarda Bastarda 9", "Texturina", "Metamorphous", "MedievalSharp", "Uncial Antiqua", "Almendra Display", "Eagle Lake", "Kings", "Lancelot"];
// Already used by EAC sites or style families: always in the list.
const FORCE = [
  "Old Standard TT", "Bodoni Moda", "Abril Fatface", "Oswald", "Libre Franklin", "Archivo Narrow", "Courier Prime", "IBM Plex Mono", "IBM Plex Sans", "IBM Plex Serif",
  "Lato", "Josefin Sans", "Montserrat", "Raleway", "Cormorant Garamond", "EB Garamond", "Spectral", "Playfair Display", "Cinzel", "IM Fell English", "Space Mono",
  "Source Sans 3", "Source Serif 4", "Inter", "Fraunces", "Libre Baskerville", "Crimson Pro", "Lora", "Merriweather", "Noto Serif", "Noto Sans", "Noto Sans Mono",
];

const ok = (f) => f.isOpenSource !== false && !f.isBrandFont && (f.subsets || []).includes("latin") && !f.primaryScript && !(f.colorCapabilities || []).length && f.category !== "Symbols";
const byName = new Map(meta.map((f) => [f.family, f]));
const pick = new Map();
const add = (f, cat) => { if (f && !pick.has(f.family)) pick.set(f.family, { f, cat }); };

for (const name of BLACKLETTER) add(byName.get(name), "blackletter");
for (const name of FORCE) { const f = byName.get(name); if (f) add(f, CATEGORY[f.category] || "display"); else console.error("FORCE missing:", name); }
const pool = meta.filter((f) => ok(f) && !f.isNoto).sort((a, b) => a.popularity - b.popularity);
const counts = {};
for (const [, v] of pick) counts[v.cat] = (counts[v.cat] || 0) + 1;
for (const f of pool) {
  const cat = CATEGORY[f.category]; if (!cat) continue;
  if ((counts[cat] || 0) >= PER_CATEGORY[cat]) continue;
  if (pick.has(f.family)) continue;
  add(f, cat); counts[cat] = (counts[cat] || 0) + 1;
}

const rows = [...pick.values()].map(({ f, cat }) => {
  const keys = Object.keys(f.fonts || {});
  const weights = [...new Set(keys.filter((k) => /^\d+$/.test(k)).map(Number))].sort((a, b) => a - b);
  const italics = [...new Set(keys.filter((k) => /^\d+i$/.test(k)).map((k) => Number(k.slice(0, -1))))].sort((a, b) => a - b);
  return { family: f.family, cat, weights: weights.length ? weights : italics, italics, pop: f.popularity };
}).sort((a, b) => a.cat.localeCompare(b.cat) || a.pop - b.pop);

const out = [];
out.push("// GENERATED by packages/fonts/scripts/build-catalogue.mjs from Google Fonts'");
out.push(`// metadata (${new Date().toISOString().slice(0, 10)}). Edit the script, not this file.`);
out.push("// Row: [family, category, weights, italic weights], weights comma-separated.");
out.push("// Within a category rows are in Google's popularity order.");
out.push("");
out.push("export const GOOGLE_ROWS: ReadonlyArray<readonly [string, string, string, string]> = [");
for (const r of rows) out.push(`  [${JSON.stringify(r.family)}, "${r.cat}", "${r.weights.join(",")}", "${r.italics.join(",")}"],`);
out.push("];");
console.log(out.join("\n"));
console.error("rows:", rows.length, JSON.stringify(rows.reduce((m, r) => ((m[r.cat] = (m[r.cat] || 0) + 1), m), {})));
