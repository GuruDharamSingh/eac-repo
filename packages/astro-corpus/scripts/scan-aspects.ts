/**
 * Which aspects each pair of bodies can form, established by casting the sky
 * every other day from 1800 to 2200 with the engine's own orbs.
 *
 *   pnpm --filter @elkdonis/astro-corpus scan:aspects
 *
 * Writes src/aspect-occurrence.ts: per canonical pair, the aspects seen at any
 * time in the window (`ever`), those seen in birth years 1900–2030 (`births`),
 * and the widest separation reached. The registry reads it to mark aspects that
 * cannot occur (Sun–Mercury trine) and aspects no living person has
 * (outer–outer pairs that did not form in those years).
 *
 * The angles are not scanned: the Ascendant and Midheaven go round the zodiac
 * every day, so every aspect to them occurs.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { calculateChart } from "@elkdonis/astro/server";
import type { AspectKey } from "@elkdonis/astro";
import { canonicalPair } from "../src/factors";

const FROM = Date.UTC(1800, 0, 1);
const TO = Date.UTC(2200, 0, 1);
const STEP_DAYS = 2;
const BIRTHS = [1900, 2030] as const;

const ever = new Map<string, Set<AspectKey>>();
const births = new Map<string, Set<AspectKey>>();
const maxSep = new Map<string, number>();

const started = Date.now();
let charts = 0;

for (let t = FROM; t < TO; t += STEP_DAYS * 86_400_000) {
  const d = new Date(t);
  const date = d.toISOString().slice(0, 10);
  const chart = calculateChart({ date, time: "12:00", timezone: "UTC", latitude: 0, longitude: 0 });
  charts++;
  const year = d.getUTCFullYear();
  const inBirths = year >= BIRTHS[0] && year <= BIRTHS[1];

  for (const a of chart.aspects) {
    if (a.a === "ascendant" || a.a === "midheaven" || a.b === "ascendant" || a.b === "midheaven") continue;
    const [x, y] = canonicalPair(a.a, a.b);
    const k = `${x}:${y}`;
    if (!ever.has(k)) ever.set(k, new Set());
    ever.get(k)!.add(a.type);
    if (inBirths) {
      if (!births.has(k)) births.set(k, new Set());
      births.get(k)!.add(a.type);
    }
  }

  const bodies = chart.bodies;
  for (let i = 0; i < bodies.length; i++) {
    for (let j = i + 1; j < bodies.length; j++) {
      const [x, y] = canonicalPair(bodies[i].key, bodies[j].key);
      const k = `${x}:${y}`;
      const d0 = Math.abs(bodies[i].longitude - bodies[j].longitude) % 360;
      const sep = d0 > 180 ? 360 - d0 : d0;
      if (sep > (maxSep.get(k) ?? -1)) maxSep.set(k, sep);
      if (!ever.has(k)) ever.set(k, new Set());
    }
  }

  if (charts % 10_000 === 0) console.log(`  ${date}  ${charts} charts`);
}

const ASPECT_ORDER: AspectKey[] = ["conjunction", "sextile", "square", "trine", "opposition", "quincunx", "semisextile", "semisquare", "sesquisquare"];
const sorted = (s: Set<AspectKey> | undefined) => ASPECT_ORDER.filter((a) => s?.has(a));

const rows = [...maxSep.keys()].sort().map((k) => {
  const e = JSON.stringify(sorted(ever.get(k)));
  const b = JSON.stringify(sorted(births.get(k)));
  return `  "${k}": { ever: ${e}, births: ${b}, maxSeparation: ${maxSep.get(k)!.toFixed(2)} },`;
});

const out = `// Generated by scripts/scan-aspects.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Sky cast every ${STEP_DAYS} days, 1800-01-01 to 2200-01-01 (${charts} charts), engine orbs.
// ever: aspects formed at any time in the window; births: formed in ${BIRTHS[0]}–${BIRTHS[1]}.
import type { AspectKey } from "@elkdonis/astro";

export const ASPECT_OCCURRENCE: Record<string, { ever: AspectKey[]; births: AspectKey[]; maxSeparation: number }> = {
${rows.join("\n")}
};
`;

const here = path.dirname(fileURLToPath(import.meta.url));
writeFileSync(path.join(here, "../src/aspect-occurrence.ts"), out);
console.log(`${charts} charts in ${((Date.now() - started) / 1000).toFixed(0)} s; ${rows.length} pairs written`);
