// Drives the Opens bridge and popups (2026-11-06). Run: ALIAS=<review stub> W=<scratch> bash ../frankenstein/run.sh featured/entry-opens.tsx:fo.js -- opens.cjs
const { chromium } = require("playwright-core");
const fs = require("fs");
const { serve } = require("./serve.cjs");
const css = ["/h/elk.css", "/h/fo.css"].map((f) => fs.readFileSync(f, "utf8").replace(/@import[^;]*;/g, "")).join("\n");
const page = `<!doctype html><meta charset=utf-8><style>${css}</style><body><div id="host"></div><script src=/fo.js></script>`;
let pass = 0, fail = 0;
const ok = (name, cond, extra = "") => { cond ? pass++ : fail++; console.log(`${cond ? "pass" : "  FAIL"} ${name}${extra ? "  " + extra : ""}`); };
(async () => {
  const srv = await serve("/h", page); fs.mkdirSync("/h/shots", { recursive: true });
  const b = await chromium.connectOverCDP("http://127.0.0.1:9222"); const p = b.contexts()[0].pages()[0];
  p.setDefaultTimeout(8000); await p.setViewportSize({ width: 1280, height: 860 });
  const errs = []; p.on("pageerror", (e) => errs.push((e.stack || e.message).slice(0, 300))); p.on("console", (m) => { if (m.type() === "error" && !/ERR_INTERNET|Failed to load resource/.test(m.text())) errs.push(m.text().slice(0, 200)); });
  await p.goto("http://127.0.0.1:8123/", { waitUntil: "domcontentloaded" }); await p.waitForSelector("#b-reviews a");
  const nav = () => p.evaluate(() => globalThis.__nav.slice());
  const dialog = () => p.locator("dialog[open]").first();
  ok("link goes to the record's page without scripts", (await p.getAttribute("#b-reviews a", "href")) === "/tours/heritage");
  await p.click("#b-reviews a"); await p.waitForTimeout(700);
  ok("click opens the reviews popup instead", (await dialog().count()) === 1 && (await nav()).length === 0, JSON.stringify(await nav()));
  ok("it lists the reviews of that tour", /Unhurried and full of stories/.test(await dialog().innerText().catch(() => "")));
  ok("with the Then button to the tour page", (await dialog().locator('a[href="/tours/heritage"]', { hasText: "See the tour and book" }).count()) === 1);
  ok("the reviews were asked for that target", JSON.stringify(await p.evaluate(() => globalThis.__reviewCalls)) === JSON.stringify([{ type: "tour", id: "elkNapol001tour000003" }]));
  await p.screenshot({ path: "/h/shots/fo-1-reviews.png" });
  await p.keyboard.press("Escape"); await p.waitForTimeout(400);
  ok("Escape closes it", (await dialog().count()) === 0);
  await p.click("#fp a"); await p.waitForTimeout(700);
  ok("a Featured person's name opens the person popup", (await dialog().count()) === 1 && /Walks every day/.test(await dialog().innerText().catch(() => "")));
  ok("person popup offers their page", (await dialog().locator('a[href="/about/danamccool"]').count()) >= 1);
  await p.screenshot({ path: "/h/shots/fo-2-person.png" });
  await p.keyboard.press("Escape"); await p.waitForTimeout(400);
  await p.click("#b-plain a"); await p.waitForTimeout(300);
  ok("a plain button follows its link", (await dialog().count()) === 0 && (await nav()).includes("/typed"));
  await p.click("#b-unknown a"); await p.waitForTimeout(300);
  ok("a popup kind the site does not offer follows the link", (await dialog().count()) === 0 && (await nav()).includes("/somewhere"));
  await p.click("#b-reviews a", { modifiers: ["Control"] }); await p.waitForTimeout(300);
  ok("Ctrl-click follows the link (new tab)", (await dialog().count()) === 0);
  ok("no page errors", errs.length === 0, errs.slice(0, 3).join(" | "));
  console.log(`\n${pass} passed, ${fail} failed`);
  srv.close(); await b.close(); process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
