#!/usr/bin/env python3
"""Scopes elktours' phone stylesheets under [data-mock-app="elktours"] for the Development app's mock tiles.
Run from anywhere: python3 scope-css.py  (reads apps/elktours/src, writes next to this file).
Rules: max-width:767px media is unwrapped (the tile draws the phone layout), min-width media and the light
theme rules are dropped, html/body:has(.elk-m) selectors become the wrapper itself."""
import re, os, sys
ROOT = os.path.expanduser("~/eac")
SRC = ROOT + "/apps/elktours/src"
OUT = ROOT + "/apps/development/src/registry/mocks/elktours"
SC = (chr(91)+"data-mock-app="+chr(34)+"elktours"+chr(34)+chr(93)+" .em-phone")

def strip_comments(s): return re.sub(r"/\*.*?\*/", "", s, flags=re.S)

def split_blocks(s):
    """Yield (prelude, body|None) at the top level."""
    i, n, out = 0, len(s), []
    while i < n:
        j = i
        while j < n and s[j] not in "{;": j += 1
        if j >= n: break
        if s[j] == ";":
            out.append((s[i:j].strip(), None)); i = j + 1; continue
        depth, k = 1, j + 1
        while k < n and depth:
            if s[k] == "{": depth += 1
            elif s[k] == "}": depth -= 1
            k += 1
        out.append((s[i:j].strip(), s[j + 1:k - 1])); i = k
    return out

def split_sel(sel):
    parts, depth, cur = [], 0, ""
    for ch in sel:
        if ch in "([": depth += 1
        if ch in ")]": depth -= 1
        if ch == "," and depth == 0: parts.append(cur); cur = ""
        else: cur += ch
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]

def scope_sel(sel):
    if "data-m-theme" in sel: return None
    if re.match(r"^(html|body)\b", sel) or sel.startswith(":root"):
        t = re.sub(r"^html(\[[^\]]*\])?(:has\([^)]*\))?\s*", "", sel)
        t = re.sub(r"^body(:has\([^)]*\))*", "", t)
        t = t.strip()
        if sel.startswith(":root"): t = sel[5:].strip()
        out = SC + (" " + t if t else "")
        return out if out.count("(") == out.count(")") else None
    return SC + " " + sel

def process(s, in_phone_media=False):
    out = []
    for pre, body in split_blocks(s):
        if body is None: continue
        if pre.startswith("@media"):
            if "min-width" in pre: continue
            if "max-width" in pre and "767" in pre:
                out.append(process(body)); continue
            inner = process(body)
            if inner.strip(): out.append(pre + " {\n" + inner + "}\n")
        elif pre.startswith("@keyframes"):
            out.append(pre + " {" + body + "}\n")
        elif pre.startswith("@"):
            continue
        else:
            sels = [x for x in (scope_sel(p) for p in split_sel(pre)) if x]
            if sels: out.append(",\n".join(sels) + " {" + body + "}\n")
    return "".join(out)

def run(src, dst, head=""):
    css = strip_comments(open(SRC + "/" + src, encoding="utf-8").read())
    css = re.sub(r"@import[^;]*;", "", css)
    open(OUT + "/" + dst, "w", encoding="utf-8").write(
        "/* GENERATED by scope-css.py from apps/elktours/src/" + src + ". Do not edit; re-run the script. */\n" + head + process(css).replace("position: fixed", "position: absolute"))

run("components/mobile/mobile.css", "phone.scoped.css")
run("components/mobile/shapes.css", "shapes.scoped.css")
run("blocks/mobile/blocks.css", "phone-blocks.scoped.css")
print("ok")
