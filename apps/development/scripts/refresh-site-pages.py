#!/usr/bin/env python3
"""Bakes src/data/site-pages.json: for each site in scripts/site-pages.seed.json, the pages and the ORDER of the
blocks each page uses. Run on eris:   python3 apps/development/scripts/refresh-site-pages.py
then:                                  python3 apps/development/scripts/scope-site-css.py
Block order for "puck" pages is read from the database (SELECT only, site_config key puck:<slug>): only block TYPES are
kept, depth first, a block that holds other blocks is replaced by what it holds. No stored content is copied.
Code-drawn pages (no database row) are listed in the seed with their own markup or block ids."""
import datetime, json, os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
seed = json.load(open(HERE + "/site-pages.seed.json"))
MAX = 14

def docker(args, inp=None):
    return subprocess.run(["sudo", "-n", "docker"] + args, input=inp, capture_output=True, text=True, check=True).stdout

U = docker(["exec", "eac-postgres", "printenv", "POSTGRES_USER"]).strip()
D = docker(["exec", "eac-postgres", "printenv", "POSTGRES_DB"]).strip()

def sql(q):
    return docker(["exec", "-i", "eac-postgres", "psql", "-U", U, "-d", D, "-At"], q)

def is_node(v):
    return isinstance(v, dict) and isinstance(v.get("type"), str) and isinstance(v.get("props"), dict)

def children(node):
    out = []
    def walk(v):
        if isinstance(v, list):
            for x in v: walk(x)
        elif is_node(v): out.append(v)
        elif isinstance(v, dict):
            for x in v.values(): walk(x)
    walk(node["props"])
    return out

def types(doc):
    out = []
    def visit(n):
        kids = children(n)
        if kids:
            for k in kids: visit(k)
        else: out.append(n["type"])
    for n in doc.get("content", []):
        if is_node(n): visit(n)
    return out

result = {"generated": datetime.datetime.utcnow().isoformat() + "Z",
          "note": "Generated by scripts/refresh-site-pages.py from the database (block types and order only) and scripts/site-pages.seed.json.",
          "sites": {}}
for app, s in seed["sites"].items():
    pages = []
    for p in s["pages"]:
        if p.get("puck"):
            org = re.sub(r"[^a-z0-9-]", "", s["orgId"]); key = re.sub(r"[^a-z0-9/-]", "", p["puck"])
            row = sql("select value::text from site_config where org_id='%s' and key='puck:%s' limit 1" % (org, key)).strip()
            try: ids = types(json.loads(row)) if row else []
            except Exception: ids = []
            total = len(ids)
            pages.append({"slug": p["slug"], "label": p["label"],
                          "source": "site_config puck:%s (%d blocks%s)" % (p["puck"], total, ", first %d shown" % MAX if total > MAX else ""),
                          "blocks": [{"id": i} for i in ids[:MAX]]})
        else:
            pages.append(p)
    result["sites"][app] = {"label": s["label"], "css": s["css"], "frame": s["frame"], "pages": pages}
json.dump(result, open(HERE + "/../src/data/site-pages.json", "w"), indent=1)
for a, s in result["sites"].items():
    print(a + ": " + " ".join("%s(%d)" % (p["slug"], len(p["blocks"])) for p in s["pages"]))

