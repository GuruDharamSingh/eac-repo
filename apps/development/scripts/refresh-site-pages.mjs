// Bakes src/data/site-pages.json: for each site in scripts/site-pages.seed.json, the pages and the ORDER of the
// blocks each page uses. Run on eris, from apps/development:   node scripts/refresh-site-pages.mjs
// then:                                                          python3 scripts/scope-site-css.py
// Block order for "puck" pages is read from the database (SELECT only, site_config key puck:<slug>): only block
// TYPES are kept, depth first, containers (a block that holds other blocks) replaced by what they hold. No stored
// content is copied. Code-drawn pages (no database row) are listed in the seed with their own markup or block ids.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(readFileSync(join(here, "site-pages.seed.json"), "utf8"));
const MAX = 14;

const docker = (args, input) => execFileSync("sudo", ["-n", "docker", ...args], { input, encoding: "utf8", maxBuffer: 64 << 20 });
const U = docker(["exec", "eac-postgres", "printenv", "POSTGRES_USER"]).trim();
const D = docker(["exec", "eac-postgres", "printenv", "POSTGRES_DB"]).trim();
const sql = (q) => docker(["exec", "-i", "eac-postgres", "psql", "-U", U, "-d", D, "-At", "-F", "\t"], q);

const isNode = (v) => v && typeof v === "object" && !Array.isArray(v) && typeof v.type === "string" && v.props && typeof v.props === "object";
function children(node) {
  const out = [];
  const walk = (v) => {
    if (Array.isArray(v)) v.forEach(walk);
    else if (isNode(v)) out.push(v);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  };
  walk(node.props);
  return out;
}
function types(doc) {
  const out = [];
  const visit = (n) => {
    const kids = children(n);
    if (kids.length) kids.forEach(visit);
    else out.push(n.type);
  };
  (doc.content ?? []).filter(isNode).forEach(visit);
  return out;
}

const result = { generated: new Date().toISOString(), note: "Generated by scripts/refresh-site-pages.mjs from the database (block types and order only) and scripts/site-pages.seed.json.", sites: {} };
for (const [app, s] of Object.entries(seed.sites)) {
  const pages = [];
  for (const p of s.pages) {
    if (p.puck) {
      const row = sql(`select value::text from site_config where org_id='${s.orgId.replace(/'/g, "")}' and key='puck:${p.puck.replace(/[^a-z0-9/-]/g, "")}' limit 1`).trim();
      let ids = [];
      try { ids = row ? types(JSON.parse(row)) : []; } catch { ids = []; }
      const total = ids.length;
      pages.push({ slug: p.slug, label: p.label, source: `site_config puck:${p.puck} (${total} blocks${total > MAX ? `, first ${MAX} shown` : ""})`, blocks: ids.slice(0, MAX).map((id) => ({ id })) });
    } else pages.push(p);
  }
  result.sites[app] = { label: s.label, css: s.css, frame: s.frame, pages };
}
writeFileSync(join(here, "../src/data/site-pages.json"), JSON.stringify(result, null, 1));
console.log(Object.entries(result.sites).map(([a, s]) => `${a}: ${s.pages.map((p) => `${p.slug}(${p.blocks.length})`).join(" ")}`).join("\n"));
